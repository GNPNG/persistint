#!/usr/bin/env node
/**
 * Node port of tools/gen_sources.py, same inputs, same SOURCES.md text, byte for byte: write a
 * SOURCES.md next to the shipped assets (release checklist LP-04, sops/09): for every image,
 * sound and video under project/assets/ and project/audio/, what made it and when.
 *
 * Sources, most specific first:
 *   1. a prompt file whose front matter names the asset (`game:`): the generator (`tool:`) and
 *      the prompt file;
 *   2. a voice clip: audio/voice/manifest.json (speaker and line) spoken by Coqui XTTS v2 with
 *      tools/generate_voice_clips.py; voice/clones/ copies are baked by tools/bake_clone_voices.py;
 *   3. a tool under tools/ (*.py, *.sh, as the Python tool reads them) that names the asset's path
 *      (exactly, by a file-name prefix, or, least specific, its folder; ties are all listed);
 *   4. otherwise "not traced", so the gap shows.
 * "Added" is the date of the commit that first added the file. A SOURCES.md without the generated
 * header line (a hand-written one, e.g. assets/canon, audio/sfx) is left alone.
 *
 *   node tools/gen_sources.mjs [--check]   # --check: exit 1 if any file would change
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { ROOT, PROJECT, rel, rglob, isFile, readText, writeText, reEscape, cmpParts } from "./lib_paths.mjs";

const MEDIA = new Set([".png", ".jpg", ".jpeg", ".webp", ".svg", ".wav", ".mp3", ".ogg", ".ogv", ".mp4"]);
const SKIP_DIRS = new Set(["test"]);
const HEADER = "<!-- generated by tools/gen_sources.py; edit the inputs, not this file -->";

function mediaFiles() {
  const byDir = new Map();
  for (const base of ["assets", "audio"]) {
    for (const p of rglob(path.join(PROJECT, base))) {
      if (!MEDIA.has(path.extname(p).toLowerCase()) || !isFile(p)) continue;
      if (rel(p, PROJECT).split("/").some((part) => SKIP_DIRS.has(part))) continue;
      const d = path.dirname(p);
      if (!byDir.has(d)) byDir.set(d, []);
      byDir.get(d).push(p);
    }
  }
  return byDir;
}

function firstAdded() {
  const out = execFileSync("git", ["-c", "core.quotepath=true", "log", "--reverse", "--diff-filter=A", "--name-only", "--format=@%ad",
    "--date=short", "--", "project/assets", "project/audio"], { cwd: ROOT, maxBuffer: 1 << 28 }).toString();
  const added = new Map();
  let date = "";
  for (const line of out.split("\n")) {
    if (line.startsWith("@")) date = line.slice(1).trim();
    else if (line.trim() && !added.has(line.trim())) added.set(line.trim(), date);
  }
  return added;
}

function prompts() {
  const found = new Map();
  for (const p of rglob(path.join(ROOT, "prompts")).filter((f) => f.endsWith(".md") && isFile(f))) {
    const text = readText(p);
    const game = text.match(/^game: ([^\n]*)$/m);
    if (!game) continue;
    const tool = text.match(/^tool: ([^\n]*)$/m);
    const drop = text.match(/^drop: ([^\n]*)$/m);
    const landed = drop === null || fs.existsSync(path.join(ROOT, drop[1].trim()));
    found.set(game[1].trim(), [tool ? tool[1].trim() : "generator not named", rel(p), landed]);
  }
  return found;
}

function toolMentions() {
  const out = new Map();
  const tools = fs.readdirSync(path.join(ROOT, "tools")).filter((n) => /\.(py|sh)$/.test(n) && isFile(path.join(ROOT, "tools", n)))
    .map((n) => `tools/${n}`).sort(cmpParts);
  for (const t of tools) {
    if (t === "tools/gen_sources.py") continue;
    const text = fs.readFileSync(path.join(ROOT, t)).toString("utf8").replace(/\r\n?/g, "\n");
    const frags = new Set((text.match(/project\/(?:assets|audio)\/[A-Za-z0-9_./-]+/g) || []).map((f) => f.replace(/\.+$/, "")));
    if (frags.size) out.set(t, [frags, text]);
  }
  return out;
}

const word = (s, text) => new RegExp(`\\b${reEscape(s)}\\b`).test(text);

function prefixNamed(name, text) {
  const parts = name.split("_");
  for (let n = parts.length - 1; n > 1; n--) if (word(parts.slice(0, n).join("_"), text)) return true;
  return false;
}

function byTool(r, mentions) {
  const stem = r.includes(".") ? r.slice(0, r.lastIndexOf(".")) : r;
  const folder = r.slice(0, r.lastIndexOf("/")) + "/";
  const name = stem.slice(stem.lastIndexOf("/") + 1);
  const us = name.indexOf("_");
  const tail = us >= 0 ? name.slice(us + 1) : name;
  const slashes = (s) => s.split("/").length - 1;
  let best = 0, hits = [];
  for (const [tool, [frags, text]] of mentions) {
    let score = 0;
    for (const f of frags) {
      if (f === r || f === stem) score = Math.max(score, 3);
      else if (stem.startsWith(f) && !f.endsWith("/") && slashes(f) === slashes(stem)) score = Math.max(score, 2);
      else if (f.replace(/\/+$/, "") + "/" === folder) {
        score = Math.max(score, word(name, text) ? 2.5 : tail.length > 3 && word(tail, text) ? 1.25 : prefixNamed(name, text) ? 1.1 : 1);
      }
    }
    if (score > best) { best = score; hits = [tool]; } else if (score === best && score > 0) hits.push(tool);
  }
  return hits;
}

function voiceLines() {
  const p = path.join(PROJECT, "audio", "voice", "manifest.json");
  const lines = new Map();
  if (!fs.existsSync(p)) return lines;
  for (const e of JSON.parse(readText(p))) {
    lines.set((e.clip || "").split("res://").join("project/"), [e.speaker || "", e.text || ""]);
  }
  return lines;
}

function describe(r, promptMap, mentions, voices) {
  let pending = "";
  if (promptMap.has(r)) {
    const [tool, prompt, landed] = promptMap.get(r);
    if (landed) return [tool, `\`${prompt}\``];
    pending = `; a ${tool} render is planned (\`${prompt}\`), not landed yet`;
  }
  if (r.startsWith("project/audio/voice/clones/")) {
    const parts = r.split("voice/clones/").join("voice/").split("/");
    return ["`tools/bake_clone_voices.py`", `kid-voice copy of \`${parts[parts.length - 1]}\``];
  }
  if (voices.has(r)) {
    const [speaker, text] = voices.get(r);
    const cps = [...text];
    const short = cps.length <= 60 ? text : cps.slice(0, 57).join("") + "...";
    return ["Coqui XTTS v2, `tools/generate_voice_clips.py`", `${speaker}: "${short}" (manifest.json; reference voice in data/voices.json)`];
  }
  const tools = byTool(r, mentions);
  if (tools.length) return [tools.map((t) => `\`${t}\``).join(", "), "drawn or cut by the tool (its docstring names inputs)" + pending];
  return ["not traced", pending.replace(/^[; ]+/, "")];
}

function render(folder, files, added, promptMap, mentions, voices) {
  const rows = [];
  let untraced = 0;
  for (const p of files) {
    const r = rel(p);
    const [made, src] = describe(r, promptMap, mentions, voices);
    if (made === "not traced") untraced++;
    rows.push(`| \`${path.basename(p)}\` | ${made} | ${src.split("|").join("/")} | ${added.get(r) || ""} |`);
  }
  const note = untraced ? `\n${untraced} file(s) not traced to a prompt, a voice line or a tool.\n` : "";
  return `${HEADER}\n# Sources: ${rel(folder)}\n\nWhat made each file here (release checklist LP-04, sops/09). ` +
    "Prompt files carry the generator in their front matter; tools carry their inputs in their " +
    `docstrings. Regenerate with \`python3 -I tools/gen_sources.py\`.\n${note}\n` +
    "| File | Made by | From | Added |\n|---|---|---|---|\n" + rows.join("\n") + "\n";
}

export function main(argv = process.argv.slice(2)) {
  const check = argv.includes("--check");
  const added = firstAdded(), promptMap = prompts(), mentions = toolMentions(), voices = voiceLines();
  let changed = 0;
  const lines = [];
  for (const [folder, files] of mediaFiles()) {
    const out = path.join(folder, "SOURCES.md");
    if (fs.existsSync(out) && !readText(out).includes(HEADER)) continue;
    const text = render(folder, files, added, promptMap, mentions, voices);
    if (!fs.existsSync(out) || readText(out) !== text) {
      changed++;
      if (check) lines.push(`would change: ${rel(out)}`);
      else { writeText(out, text); lines.push(`wrote ${rel(out)}`); }
    }
  }
  lines.push(`${changed} SOURCES.md file(s) ${check ? "out of date" : "written"}`);
  return { code: check && changed ? 1 : 0, out: lines.join("\n") };
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1"))) {
  const r = main();
  console.log(r.out);
  process.exit(r.code);
}
