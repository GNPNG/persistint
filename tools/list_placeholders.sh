#!/bin/sh
# Release checklist GC-11 (sops/09; bead persistint-game-d15.29): list every placeholder the game
# can still show, so each one is either replaced or kept on purpose.
#   1. Paper-doll / NPC art in project/assets/placeholder with no same-name file in assets/canon
#      (canon wins when it exists, so shadowed files never show).
#   2. PlaceholderProp nodes in project/scenes whose drop res://assets/island/prop_<art_path>.png
#      has not landed, so the prop shows its fallback art.
# Usage: sh tools/list_placeholders.sh > dev/PLACEHOLDERS.md
# Reads assets and makes none (// provenance: diagnostic-only), so gen_sources.mjs skips it.
set -eu
cd "$(dirname "$0")/.."
echo "# Placeholders still shown (GC-11)"
echo
echo "Generated by \`sh tools/list_placeholders.sh > dev/PLACEHOLDERS.md\` on $(date -u +%Y-%m-%d) at $(git rev-parse --short HEAD)."
echo "GC-11 is done when every row is replaced or its Decision reads \"kept on purpose\" (sops/09)."
echo
echo "## Placeholder art with no canon replacement"
echo
echo "| File | Referenced by (game, then tests) | Decision |"
echo "|---|---|---|"
for p in project/assets/placeholder/*.png; do
  f=$(basename "$p"); n=${f%.png}
  [ -f "project/assets/canon/$f" ] && continue
  refs=$(grep -rlw "$n" project --include=*.gd --include=*.tscn --include=*.json --include=*.tres 2>/dev/null | sed 's|^project/||')
  game=$(printf '%s\n' "$refs" | grep -v '^tests/' | grep . | tr '\n' ' ')
  tests=$(printf '%s\n' "$refs" | grep '^tests/' | grep -c . || true)
  if [ -n "$game" ]; then used="$game"
  elif [ "$tests" -gt 0 ]; then used="tests only ($tests)"
  else used="nothing: not shown in the game"; fi
  echo "| \`$f\` | $used | open |"
done
echo
echo "## Props showing fallback art (drop not landed)"
echo
echo "| Scene | Node | Waiting for | Showing now | Decision |"
echo "|---|---|---|---|---|"
for s in $(grep -rl 'placeholder_prop.gd' project/scenes --include=*.tscn); do
  awk -v scene="${s#project/}" '
    /^\[node name=/ { match($0, /name="[^"]*"/); node = substr($0, RSTART+6, RLENGTH-7) }
    /^art_path = / { gsub(/^art_path = "|"$/, ""); art = $0 }
    /^fallback_path = / { gsub(/^fallback_path = "res:\/\/|"$/, ""); print scene "\t" node "\t" art "\t" $0 }
  ' "$s"
done | while IFS="$(printf '\t')" read -r scene node art fb; do
  [ -s "project/assets/island/prop_$art.png" ] && continue
  echo "| \`$scene\` | $node | \`assets/island/prop_$art.png\` | \`$fb\` | open |"
done
