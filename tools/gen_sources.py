#!/usr/bin/env python3
"""Write a SOURCES.md next to the shipped assets (release checklist LP-04, sops/09): for every
image, sound and video under project/assets/ and project/audio/, what made it and when.

Sources, most specific first:
  1. a prompt file whose front matter names the asset (`game:`): the generator (`tool:`, e.g.
     Gemini image / Veo / Lyria) and the prompt file;
  2. a voice clip: audio/voice/manifest.json (speaker and line) spoken by Coqui XTTS v2 with
     tools/generate_voice_clips.py; voice/clones/ copies are baked by tools/bake_clone_voices.py;
  3. a tool under tools/ that names the asset's path (exactly, by a file-name prefix such as
     project/assets/florida/shell_, or, least specific, its folder; ties are all listed);
  4. otherwise "not traced", so the gap shows.
"Added" is the date of the commit that first added the file. A SOURCES.md without this tool's
header line (a hand-written one, e.g. assets/canon, audio/sfx) is left alone.

    python3 -I tools/gen_sources.py [--check]   # --check: exit 1 if any file would change
"""
import json
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROJECT = ROOT / "project"
MEDIA = {".png", ".jpg", ".jpeg", ".webp", ".svg", ".wav", ".mp3", ".ogg", ".ogv", ".mp4"}
SKIP_DIRS = {"test"}  # review scenes' assets stay out of the player build
HEADER = "<!-- generated by tools/gen_sources.py; edit the inputs, not this file -->"


def media_files():
    by_dir = defaultdict(list)
    for base in ("assets", "audio"):
        for p in sorted((PROJECT / base).rglob("*")):
            if p.suffix.lower() in MEDIA and p.is_file() and not SKIP_DIRS & set(p.relative_to(PROJECT).parts):
                by_dir[p.parent].append(p)
    return by_dir


def first_added():
    out = subprocess.run(["git", "log", "--reverse", "--diff-filter=A", "--name-only", "--format=@%ad",
                          "--date=short", "--", "project/assets", "project/audio"],
                         cwd=ROOT, capture_output=True, text=True, check=True).stdout
    added, date = {}, ""
    for line in out.splitlines():
        if line.startswith("@"):
            date = line[1:]
        elif line.strip():
            added.setdefault(line.strip(), date)
    return added


def prompts():
    found = {}
    for p in sorted((ROOT / "prompts").rglob("*.md")):
        text = p.read_text(encoding="utf-8", errors="replace")
        game = re.search(r"^game: (.*)$", text, re.M)
        if game:
            tool = re.search(r"^tool: (.*)$", text, re.M)
            drop = re.search(r"^drop: (.*)$", text, re.M)
            landed = drop is None or (ROOT / drop.group(1).strip()).exists()
            found[game.group(1).strip()] = (tool.group(1).strip() if tool else "generator not named",
                                            str(p.relative_to(ROOT)), landed)
    return found


def tool_mentions():
    """tool path -> (set of project/... path fragments it names, the tool's text)."""
    out = {}
    for t in sorted(list((ROOT / "tools").glob("*.py")) + list((ROOT / "tools").glob("*.sh"))):
        if t.name == Path(__file__).name:
            continue
        text = t.read_text(errors="replace")
        frags = set(re.findall(r"project/(?:assets|audio)/[A-Za-z0-9_./-]+", text))
        if frags:
            out[str(t.relative_to(ROOT))] = ({f.rstrip(".") for f in frags}, text)
    return out


def by_tool(rel: str, mentions: dict) -> list:
    """The tools that name rel, most specific match only."""
    stem = rel.rsplit(".", 1)[0]
    folder = rel.rsplit("/", 1)[0] + "/"
    best, hits = 0, []
    name = stem.rsplit("/", 1)[-1]
    tail = name.split("_", 1)[-1]
    for tool, (frags, text) in mentions.items():
        score = 0
        for f in frags:
            if f in (rel, stem):
                score = max(score, 3)
            elif stem.startswith(f) and not f.endswith("/") and f.count("/") == stem.count("/"):
                score = max(score, 2)
            elif f.rstrip("/") + "/" == folder:
                # by folder only: a tool that also spells the file's name (or its name past the
                # first prefix, as generators often build "bg_" + name) is the likelier writer
                score = max(score, 2.5 if re.search(rf"\b{re.escape(name)}\b", text)
                            else 1.25 if len(tail) > 3 and re.search(rf"\b{re.escape(tail)}\b", text)
                            else 1.1 if _prefix_named(name, text) else 1)
        if score > best:
            best, hits = score, [tool]
        elif score == best and score > 0:
            hits.append(tool)
    return hits


def _prefix_named(name: str, text: str) -> bool:
    """The name with trailing _parts dropped (plot_ready_mango -> plot_ready) is spelled in text."""
    parts = name.split("_")
    for n in range(len(parts) - 1, 1, -1):
        if re.search(rf"\b{re.escape('_'.join(parts[:n]))}\b", text):
            return True
    return False


def voice_lines():
    path = PROJECT / "audio" / "voice" / "manifest.json"
    if not path.exists():
        return {}
    lines = {}
    for e in json.loads(path.read_text(encoding="utf-8")):
        clip = e.get("clip", "").replace("res://", "project/")
        lines[clip] = (e.get("speaker", ""), e.get("text", ""))
    return lines


def describe(rel, prompt_map, mentions, voices):
    pending = ""
    if rel in prompt_map:
        tool, prompt, landed = prompt_map[rel]
        if landed:
            return tool, f"`{prompt}`"
        # the prompt is registered but its render has not been dropped in: what ships is the
        # stand-in a tool draws at the same path
        pending = f"; a {tool} render is planned (`{prompt}`), not landed yet"
    if rel.startswith("project/audio/voice/clones/"):
        return "`tools/bake_clone_voices.py`", "kid-voice copy of `%s`" % rel.replace("voice/clones/", "voice/").split("/")[-1]
    if rel in voices:
        speaker, text = voices[rel]
        short = text if len(text) <= 60 else text[:57] + "..."
        return "Coqui XTTS v2, `tools/generate_voice_clips.py`", f"{speaker}: \"{short}\" (manifest.json; reference voice in data/voices.json)"
    tools = by_tool(rel, mentions)
    if tools:
        return ", ".join(f"`{t}`" for t in tools), "drawn or cut by the tool (its docstring names inputs)" + pending
    return "not traced", pending.lstrip("; ")


def render(folder: Path, files: list, added, prompt_map, mentions, voices) -> str:
    rows, untraced = [], 0
    for p in files:
        rel = str(p.relative_to(ROOT))
        made, src = describe(rel, prompt_map, mentions, voices)
        untraced += made == "not traced"
        rows.append(f"| `{p.name}` | {made} | {src.replace('|', '/')} | {added.get(rel, '')} |")
    title = str(folder.relative_to(ROOT))
    note = f"\n{untraced} file(s) not traced to a prompt, a voice line or a tool.\n" if untraced else ""
    return (f"{HEADER}\n# Sources: {title}\n\nWhat made each file here (release checklist LP-04, sops/09). "
            f"Prompt files carry the generator in their front matter; tools carry their inputs in their "
            f"docstrings. Regenerate with `python3 -I tools/gen_sources.py`.\n{note}\n"
            "| File | Made by | From | Added |\n|---|---|---|---|\n" + "\n".join(rows) + "\n")


def main() -> int:
    check = "--check" in sys.argv
    added, prompt_map, mentions, voices = first_added(), prompts(), tool_mentions(), voice_lines()
    changed = 0
    for folder, files in media_files().items():
        out = folder / "SOURCES.md"
        if out.exists() and HEADER not in out.read_text(encoding="utf-8"):
            continue  # hand-written
        text = render(folder, files, added, prompt_map, mentions, voices)
        if not out.exists() or out.read_text(encoding="utf-8") != text:
            changed += 1
            if check:
                print(f"would change: {out.relative_to(ROOT)}")
            else:
                out.write_text(text, encoding="utf-8")
                print(f"wrote {out.relative_to(ROOT)}")
    print(f"{changed} SOURCES.md file(s) {'out of date' if check else 'written'}")
    return 1 if check and changed else 0


if __name__ == "__main__":
    sys.exit(main())
